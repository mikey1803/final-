import { Fragment } from 'react'
import { PageHeader } from '../components/ui/PageHeader'
import { Metric } from '../components/ui/Metric'
import { DataTable } from '../components/ui/DataTable'
import { useJson } from '../hooks/useJson'
import { FAILURE_TYPES } from '../data/failureTypes'

// Matches --color-lav-surface / --color-lav-primary in index.css. Hardcoded
// (not read from the CSS variable) the same way lib/colors.js's
// METHOD_COLORS already is — this dashboard has no runtime theme switch to
// track, just a fixed dark palette, so a literal interpolation target is
// simpler than a getComputedStyle round-trip for no behavioral difference.
const CELL_BASE = [16, 18, 21]
const CELL_TARGET = [76, 111, 255]

function cellColor(value) {
  const [r0, g0, b0] = CELL_BASE
  const [r1, g1, b1] = CELL_TARGET
  const r = Math.round(r0 + (r1 - r0) * value)
  const g = Math.round(g0 + (g1 - g0) * value)
  const b = Math.round(b0 + (b1 - b0) * value)
  return `rgb(${r}, ${g}, ${b})`
}

function labelFor(id) {
  return FAILURE_TYPES.find((f) => f.id === id)?.label ?? id
}

function ConfusionMatrix({ labels, matrix }) {
  return (
    <div className="overflow-x-auto">
      <div
        className="grid gap-px overflow-hidden rounded-md border border-lav-border bg-lav-border"
        style={{ gridTemplateColumns: `140px repeat(${labels.length}, minmax(64px, 1fr))`, minWidth: 640 }}
      >
        <div className="bg-lav-bg px-2 py-2" />
        {labels.map((l) => (
          <div key={l} className="flex items-end justify-center bg-lav-bg px-1 py-2 text-center font-mono text-[10px] leading-tight text-lav-muted">
            {labelFor(l)}
          </div>
        ))}
        {matrix.map((row, i) => (
          <Fragment key={labels[i]}>
            <div className="flex items-center bg-lav-bg px-2 py-1 font-mono text-[10px] text-lav-muted">
              {labelFor(labels[i])}
            </div>
            {row.map((value, j) => (
              <div
                key={`${labels[i]}-${labels[j]}`}
                title={`true ${labelFor(labels[i])} -> predicted ${labelFor(labels[j])}: ${Math.round(value * 100)}%`}
                className="flex items-center justify-center px-1 py-3 font-mono text-[11px] font-medium"
                style={{ backgroundColor: cellColor(value), color: value > 0.5 ? '#fff' : 'var(--color-lav-muted)' }}
              >
                {value > 0 ? `${Math.round(value * 100)}%` : ''}
              </div>
            ))}
          </Fragment>
        ))}
      </div>
      <p className="mt-2 font-mono text-[10px] text-lav-muted">
        rows = true failure type, columns = predicted — diagonal is correct predictions
      </p>
    </div>
  )
}

/** Real held-out evaluation of the actual trained classifier: a confusion
 * matrix and per-class precision/recall/F1, generated by
 * backend/experiments/classifier_diagnostics.py from a fresh balanced
 * synthetic test set (same real classifier state.classifier in the live
 * demo uses). Companion to Classifier-Noise Sweep, which sweeps
 * classification accuracy as a controlled variable rather than reporting
 * the trained model's own measured accuracy. */
export function ClassifierDiagnostics() {
  const { data, loading, error } = useJson('classifier_diagnostics.json')

  if (loading) return <p className="font-sans text-sm text-lav-muted">Loading…</p>
  if (error) return <p className="font-sans text-sm text-red-500">Failed to load classifier diagnostics data.</p>

  const rows = data.labels.map((id) => ({
    failure_type: labelFor(id),
    precision: data.per_class[id].precision,
    recall: data.per_class[id].recall,
    f1: data.per_class[id].f1,
    support: data.per_class[id].support,
  }))

  const columns = [
    { key: 'failure_type', label: 'Failure type' },
    { key: 'precision', label: 'Precision', align: 'right', render: (r) => r.precision.toFixed(3) },
    { key: 'recall', label: 'Recall', align: 'right', render: (r) => r.recall.toFixed(3) },
    { key: 'f1', label: 'F1', align: 'right', render: (r) => r.f1.toFixed(3) },
    { key: 'support', label: 'Support', align: 'right' },
  ]

  return (
    <div>
      <PageHeader
        title="Classifier Diagnostics"
        subtitle={`Real held-out evaluation of the actual trained failure classifier — ${data.n_per_type} fresh synthetic samples per failure type (seed ${data.seed}), never seen during training. Not a sweep of simulated noise: this is the model's own measured accuracy.`}
      />

      <div className="border-t border-lav-border py-5">
        <div className="grid grid-cols-2 gap-4 sm:grid-cols-4">
          <Metric label="Accuracy" value={`${(data.macro.accuracy * 100).toFixed(1)}%`} accent="primary" />
          <Metric label="Precision (macro)" value={`${(data.macro.precision * 100).toFixed(1)}%`} accent="teal" />
          <Metric label="Recall (macro)" value={`${(data.macro.recall * 100).toFixed(1)}%`} accent="amber" />
          <Metric label="F1 (macro)" value={`${(data.macro.f1 * 100).toFixed(1)}%`} accent="success" />
        </div>
      </div>

      <div className="border-t border-lav-border py-5">
        <h3 className="mb-3 font-mono text-[10px] uppercase tracking-wider text-lav-muted">Confusion matrix</h3>
        <ConfusionMatrix labels={data.labels} matrix={data.confusion_matrix} />
      </div>

      <div className="border-t border-lav-border py-5">
        <h3 className="mb-3 font-mono text-[10px] uppercase tracking-wider text-lav-muted">Per-class precision / recall / F1</h3>
        <DataTable columns={columns} rows={rows} downloadable filename="classifier_diagnostics.csv" sortable />
      </div>
    </div>
  )
}
