"""Phase 7: taxonomy size stress test.

Does performance hold up as the number of distinct failure types (the
"taxonomy") grows well past the project's real 7? Sweeps taxonomy size
in {7, 14, 28} — synthetic integer type labels 0..N-1, since only 7 real
``FailureType`` members exist — while the recovery-strategy space stays
fixed at the real 6 ``RecoveryStrategy`` members (taxonomy size refers
to failure types only; see ``failures/taxonomy.py``).

Reuses, unmodified in logic (only backward-compatibly generalized to
accept an arbitrary type/strategy index space instead of the hardcoded
enums):
  - ``matrix_family.sample_matrix`` (already generic over n_types/n_strats)
  - ``matrix_family.simulate_selector_on_matrix`` (the same select/update
    loop and seeding as Phase 3A/5)
  - ``matrix_family.analytic_oracle_rate`` / ``analytic_random_rate``
    (the same normalization formula)
  - ``stats_utils.bootstrap_ci`` (the same 95% CI method)
  - ``static_rule_sweep.StaticPolicySelector`` (unchanged — it only ever
    wraps a plain dict, with no dependency on taxonomy size)
  - ``SelectorFactory`` / ``LinUCBBaseline`` for Thompson, Discounted
    Thompson, and LinUCB (now accepting an optional ``types``/
    ``strategies`` override, added to ``selector.py``/``baselines.py``
    specifically to make this generalization possible without
    duplicating any bandit-update math).

The Blind Static Rule policy is generated by the exact same algorithm as
Phase 5's ``generate_static_policy`` (pick which rows get the true best
strategy, assign a uniformly random wrong strategy to the rest, no
reward magnitudes consulted) — reimplemented here only because Phase
5's version is hardcoded to the 7-element ``FailureType`` list and
cannot be imported as-is for taxonomy sizes 14/28. Its quality is fixed
at the same ratio as the project's canonical blind rule (6 correct out
of 7 -> round(N * 6/7) correct out of N).
"""

import random
from pathlib import Path
from typing import Optional

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from src.evaluation.baselines import LinUCBBaseline
from src.evaluation.matrix_family import (
    _STRATS,
    analytic_oracle_rate,
    analytic_random_rate,
    sample_matrix,
    simulate_selector_on_matrix,
)
from src.evaluation.static_rule_sweep import StaticPolicySelector
from src.evaluation.stats_utils import MC_VARIATION_NOTE, bootstrap_ci
from src.recovery.selector import SelectorFactory

_TAXONOMY_SIZES: list[int] = [7, 14, 28]
_REFERENCE_QUALITY_NUM = 6  # same "6/7 correct" ratio as the project's canonical blind rule
_REFERENCE_QUALITY_DENOM = 7

_METHOD_LABELS: dict[str, str] = {
    "blind_static_rule":            "Blind Static Rule",
    "thompson_sampling":            "Thompson Sampling",
    "discounted_thompson_sampling": "Discounted Thompson Sampling",
    "linucb":                       "LinUCB",
}
_METHOD_COLORS: dict[str, str] = {
    "blind_static_rule":            "#f59e0b",
    "thompson_sampling":            "#16a34a",
    "discounted_thompson_sampling": "#7c3aed",
    "linucb":                       "#0d9488",
}


def generate_blind_policy(
    matrix: np.ndarray,
    num_correct: int,
    type_labels: list,
    strategy_labels: list,
    rng: random.Random,
) -> dict:
    """Same blind-construction algorithm as
    ``static_rule_sweep.generate_static_policy``, parameterized over a
    generic type/strategy label space instead of the fixed
    ``FailureType``/``RecoveryStrategy`` lists.
    """
    n_types, n_strats = matrix.shape
    best_idx = matrix.argmax(axis=1)
    correct_rows = set(rng.sample(range(n_types), num_correct))

    policy = {}
    for t_idx, ft in enumerate(type_labels):
        best_s = int(best_idx[t_idx])
        if t_idx in correct_rows:
            policy[ft] = strategy_labels[best_s]
        else:
            wrong_choices = [s for s in range(n_strats) if s != best_s]
            policy[ft] = strategy_labels[rng.choice(wrong_choices)]
    return policy


def _make_bandit_selector(method: str, seed: int, types: list, strategies: list):
    if method == "linucb":
        return LinUCBBaseline(alpha=1.0, seed=seed + 1500, types=types, strategies=strategies)
    return SelectorFactory.create(method, seed=seed + 500, types=types, strategies=strategies)


def run_taxonomy_size_sweep(
    taxonomy_sizes: Optional[list[int]] = None,
    n_matrices: int = 25,
    n_seeds: int = 20,
    gap: float = 0.2,
    num_episodes: int = 150,
    base_seed: int = 2026,
) -> pd.DataFrame:
    """Sweep taxonomy size; for each size, draw ``n_matrices`` randomized
    reward matrices (``sample_matrix``, generalized to ``n_types`` rows)
    shared across all 4 methods, and replay each over ``n_seeds``
    independent outcome sequences via ``simulate_selector_on_matrix``.

    Returns a long-format DataFrame: one row per
    (taxonomy_size, matrix_idx, method, seed) with the late-stage
    success rate and its normalized score.
    """
    if taxonomy_sizes is None:
        taxonomy_sizes = _TAXONOMY_SIZES
    n_strats = len(_STRATS)
    methods = list(_METHOD_LABELS.keys())

    rows: list[dict] = []

    print(f"  Taxonomy size sweep: sizes={taxonomy_sizes}  n_matrices={n_matrices}  n_seeds={n_seeds}")
    print(f"  gap={gap}  num_episodes={num_episodes}  methods={list(_METHOD_LABELS.values())}\n")

    for n_types in taxonomy_sizes:
        type_labels = list(range(n_types))
        num_correct = int(round(n_types * _REFERENCE_QUALITY_NUM / _REFERENCE_QUALITY_DENOM))

        for matrix_idx in range(n_matrices):
            matrix_seed = base_seed + n_types * 100_000 + matrix_idx * 97
            matrix_rng = np.random.default_rng(matrix_seed)
            matrix = sample_matrix(n_types=n_types, n_strats=n_strats, gap=gap, rng=matrix_rng)

            oracle_rate = analytic_oracle_rate(matrix)
            random_rate = analytic_random_rate(matrix)
            denom = oracle_rate - random_rate

            policy_rng = random.Random(matrix_seed + 1)
            policy = generate_blind_policy(matrix, num_correct, type_labels, _STRATS, policy_rng)

            for method in methods:
                for seed_idx in range(n_seeds):
                    sim_seed = matrix_seed + 1000 * (seed_idx + 1)
                    if method == "blind_static_rule":
                        selector = StaticPolicySelector(policy)
                    else:
                        selector = _make_bandit_selector(method, sim_seed, type_labels, _STRATS)

                    rate = simulate_selector_on_matrix(
                        matrix, selector, num_episodes, sim_seed,
                        type_labels=type_labels, strategy_labels=_STRATS,
                    )
                    normalized = (rate - random_rate) / denom if denom != 0 else float("nan")
                    rows.append({
                        "taxonomy_size": n_types,
                        "matrix_idx": matrix_idx,
                        "method": method,
                        "method_label": _METHOD_LABELS[method],
                        "seed": seed_idx,
                        "late_stage_success_rate": rate,
                        "normalized_score": normalized,
                    })

        print(f"  taxonomy_size={n_types:>2}  num_correct={num_correct}/{n_types}  "
              f"n_matrices={n_matrices}  n_seeds={n_seeds}")

    return pd.DataFrame(rows)


def summarize_taxonomy_size_sweep(results_df: pd.DataFrame) -> pd.DataFrame:
    """Mean normalized score + 95% bootstrap CI per (taxonomy_size, method)."""
    rows = []
    for (taxonomy_size, method), sub in results_df.groupby(["taxonomy_size", "method"]):
        vals = sub["normalized_score"].values
        ci_lo, ci_hi = bootstrap_ci(vals)
        rows.append({
            "taxonomy_size": taxonomy_size,
            "method": method,
            "method_label": _METHOD_LABELS[method],
            "n": len(vals),
            "mean_normalized_score": float(np.mean(vals)),
            "bootstrap_ci95_lower": ci_lo,
            "bootstrap_ci95_upper": ci_hi,
        })
    return pd.DataFrame(rows).sort_values(["taxonomy_size", "method"]).reset_index(drop=True)


def plot_taxonomy_size_sweep(summary_df: pd.DataFrame, save_dir: Path) -> None:
    """x-axis = taxonomy size, y-axis = normalized score, one line per method."""
    fig, ax = plt.subplots(figsize=(9, 6))
    sizes = sorted(summary_df["taxonomy_size"].unique())

    for method, label in _METHOD_LABELS.items():
        sub = summary_df[summary_df["method"] == method].set_index("taxonomy_size").reindex(sizes)
        means = sub["mean_normalized_score"].values
        lo = sub["bootstrap_ci95_lower"].values
        hi = sub["bootstrap_ci95_upper"].values
        yerr = np.vstack([means - lo, hi - means])

        ax.errorbar(
            sizes, means, yerr=yerr, fmt="o-", color=_METHOD_COLORS[method],
            linewidth=2, markersize=7, capsize=4, label=label,
        )

    ax.set_xlabel("Taxonomy size (number of failure types)", fontsize=12)
    ax.set_ylabel("Normalized score", fontsize=12)
    ax.set_title("Taxonomy Size Stress Test", fontsize=13)
    ax.set_xticks(sizes)
    ax.legend(fontsize=9, loc="best")
    ax.grid(True, alpha=0.3)
    fig.tight_layout()

    save_dir.mkdir(parents=True, exist_ok=True)
    fig_path = save_dir / "taxonomy_size_plot.png"
    fig.savefig(str(fig_path), dpi=150)
    plt.close(fig)
    print(f"  Taxonomy size plot saved to {fig_path}")


def run_phase7(
    taxonomy_sizes: Optional[list[int]] = None,
    n_matrices: int = 25,
    n_seeds: int = 20,
    gap: float = 0.2,
    num_episodes: int = 150,
    base_seed: int = 2026,
    results_dir: Optional[Path] = None,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Run the full Phase 7 taxonomy-size sweep, plot the figure, and
    save data to results/phase7/."""
    if results_dir is None:
        results_dir = Path(__file__).resolve().parent.parent.parent / "results" / "phase7"
    results_dir.mkdir(parents=True, exist_ok=True)

    results_df = run_taxonomy_size_sweep(
        taxonomy_sizes=taxonomy_sizes, n_matrices=n_matrices, n_seeds=n_seeds,
        gap=gap, num_episodes=num_episodes, base_seed=base_seed,
    )
    results_csv = results_dir / "taxonomy_size_results.csv"
    results_df.to_csv(str(results_csv), index=False)
    print(f"\n  Raw results saved to {results_csv}")

    summary_df = summarize_taxonomy_size_sweep(results_df)
    summary_csv = results_dir / "taxonomy_size_summary.csv"
    summary_df.to_csv(str(summary_csv), index=False)
    print(f"  Summary (mean normalized score, 95% CI) saved to {summary_csv}")
    print(summary_df.to_string(index=False, float_format="{:.4f}".format))

    plot_taxonomy_size_sweep(summary_df, results_dir)

    print(f"\n  NOTE: {MC_VARIATION_NOTE}")

    return results_df, summary_df
